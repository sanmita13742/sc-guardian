"""Page 2: SBOM explorer and quality assessment."""
from __future__ import annotations

import streamlit as st

from ui.components.common import df, kv_table, page_header, read_file, require_result


def render() -> None:
    page_header("SBOM Explorer", "Component inventory, CycloneDX structural validation, and quality assessment.")
    r = require_result()
    if not r:
        return

    q, comps = r.get("quality", {}), [c for c in r["components"] if c["type"] != "file" and not c.get("is_self")]
    tool = r.get("sbom_tool") or {}
    used = tool.get("used") or r.get("inventory_source")
    if used in (None, "none"):
        st.error("No SBOM could be generated for this scan (no Syft/Trivy and no parsable lockfiles/manifests).")
    else:
        label = {"syft": "Syft", "trivy": "Trivy", "builtin": "Built-in rule engine"}.get(used, used)
        ver = f" {tool.get('version')}" if tool.get("version") else ""
        st.caption(f"SBOM generated by **{label}{ver}** · requested scanner: `{tool.get('requested', 'auto')}`")

    c = st.columns(5)
    c[0].metric("Components", len(comps))
    c[1].metric("Inventory", (q.get("inventory_status") or "n/a").replace("_", " ").title())
    c[2].metric("Relationships", q.get("dependency_relationships", "n/a"))
    c[3].metric("Metadata", (q.get("metadata_status") or "n/a").replace("_", " ").title())
    c[4].metric("Unresolved", q.get("unresolved_components", 0))

    t1, t2, t3, t_raw, t4 = st.tabs(["Components", "Quality", "Scanner & validation", "SBOM file", "Downloads"])

    with t1:
        f1, f2, f3 = st.columns([1, 1, 2])
        ecos = sorted({x["ecosystem"] or x["purl_type"] or "unknown" for x in comps})
        sel_e = f1.multiselect("Ecosystem", ecos, placeholder="All ecosystems")
        svcs = sorted({x["service_dir"] or "." for x in comps})
        sel_s = f2.multiselect("Service", svcs, placeholder="All services")
        text = f3.text_input("Search package or PURL", placeholder="Filter by name...")

        rows = [x for x in comps if (not sel_e or (x["ecosystem"] or x["purl_type"] or "unknown") in sel_e)
                and (not sel_s or (x["service_dir"] or ".") in sel_s)
                and (not text or text.lower() in (x["name"] + (x["purl"] or "")).lower())]

        st.caption(f"Showing {len(rows)} of {len(comps)} components")
        df([{"Name": x["name"], "Version": x["version"], "Ecosystem": x["ecosystem"] or x["purl_type"],
             "Service": x["service_dir"], "License": ", ".join(x["licenses"]) or "n/a",
             "Supplier": x["supplier"] or "n/a", "PURL": x["purl"]} for x in rows], height=380)

        if rows:
            with st.expander("Component Inspector", expanded=False):
                pick = st.selectbox("Inspect component", [f"{x['name']}@{x['version']}" for x in rows[:300]])
                idx = [f"{x['name']}@{x['version']}" for x in rows[:300]].index(pick)
                kv_table({k: v for k, v in rows[idx].items() if k not in ("hashes",)})

    with t2:
        col_m1, col_m2 = st.columns(2)
        with col_m1:
            st.markdown(f"**Missing Lockfile Entries** ({q.get('lockfile_missing_from_sbom_count', 0)})")
            df(q.get("lockfile_missing_from_sbom", []), height=220)
        with col_m2:
            st.markdown(f"**SBOM Components Absent from Lockfiles** ({q.get('sbom_absent_from_lockfile_count', 0)})")
            df(q.get("sbom_absent_from_lockfile", []), height=220)

        st.caption(f"Relationships: {q.get('relationship_edges', 0)} edges recorded · {q.get('missing_relationships', 0)} components without relationships")

    with t3:
        v = r["sbom"].get("validation", {})
        st.markdown(f"**Spec:** CycloneDX {r['sbom'].get('spec_version') or 'n/a'} &nbsp;·&nbsp; **Valid:** {v.get('valid', False)} &nbsp;·&nbsp; **Components:** {v.get('stats', {}).get('components', 0)}")
        for e in v.get("errors", []):
            st.error(e)
        st.markdown("**Scanner attempts** (in the order tried)")
        att = tool.get("attempts") or []
        df([{"Scanner": a["scanner"], "Result": "✓ used" if a["ok"] else "✗ failed / not available", "Version": a.get("version") or "—",
             "Seconds": a.get("duration_s"), "Detail": a.get("error") or "ok"} for a in att], height="content")
        for a in att:
            if a.get("command"):
                st.code(a["command"], language="bash")
        es = tool.get("engine_stats")
        if es:
            st.markdown("**Rule engine statistics** (rules R1–R6 in `sbom/builtin_generator.py`)")
            kv_table(es)
        av = tool.get("available") or {}
        if av:
            st.caption("Installed: " + ", ".join(f"{k}={'yes' if x else 'no'}" for k, x in av.items() if k != "builtin") + ". Install Syft/Trivy for broader coverage; see README.")

    with t_raw:
        files = r.get("sbom_files") or ([{"label": "SBOM", "path": r.get("sbom_path")}] if r.get("sbom_path") else [])
        sel_path = r.get("sbom_path")
        if len(files) > 1:
            pick = st.selectbox("SBOM file", range(len(files)), format_func=lambda i: files[i]["label"])
            sel_path = files[pick]["path"]
        raw = read_file(sel_path)
        if not raw:
            st.warning("The SBOM file is no longer on disk (artifacts were cleaned). Re-run the scan with *Reuse cached scan* unticked to regenerate it.")
        else:
            import json as _json
            text = raw.decode("utf-8", "replace")
            try:
                doc = _json.loads(text)
            except ValueError:
                doc = None
            st.caption(f"`{sel_path}` · {len(raw):,} bytes · exactly as written by the scanner")
            views = ["Full file", "Header", "Components", "Dependencies"] if doc else ["Full file"]
            view = st.radio("View", views, horizontal=True)
            if view == "Full file":
                lines = text.splitlines()
                per = 400
                pages = max(1, (len(lines) + per - 1) // per)
                pg = st.number_input(f"Page ({per} lines per page, {len(lines):,} lines)", 1, pages, 1)
                st.code(chr(10).join(lines[(pg - 1) * per: pg * per]), language="json", line_numbers=True)
            elif view == "Header":
                st.json({k: x for k, x in doc.items() if k not in ("components", "dependencies")})
            elif view == "Components":
                q_ = st.text_input("Filter components by name / purl", key="rawq").lower()
                items = [c for c in doc.get("components", []) if not q_ or q_ in (str(c.get("name")) + str(c.get("purl"))).lower()]
                size = 25
                pg = st.number_input(f"Page ({size} per page, {len(items)} components)", 1, max(1, (len(items) + size - 1) // size), 1)
                st.json(items[(pg - 1) * size: pg * size])
            else:
                deps = doc.get("dependencies", [])
                size = 40
                pg = st.number_input(f"Page ({size} per page, {len(deps)} records)", 1, max(1, (len(deps) + size - 1) // size), 1, key="dep_p")
                st.json(deps[(pg - 1) * size: pg * size])

    with t4:
        data = read_file(r.get("sbom_path"))
        if data:
            st.download_button(f"Download CycloneDX JSON ({used})", data, file_name=f"{r['repo']['name']}-sbom.cdx.json", mime="application/json", use_container_width=True)
        else:
            st.info("No SBOM artifact file available.")
