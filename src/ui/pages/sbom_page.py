"""Page 2: SBOM explorer and quality assessment."""
from __future__ import annotations

import streamlit as st

from reporting.counts import package_components

from ui.components.common import df, kv_table, page_header, read_file, require_result


def render() -> None:
    page_header("SBOM Explorer", "Component inventory, CycloneDX structural validation, and quality assessment.")
    r = require_result()
    if not r:
        return

    q, comps = r.get("quality", {}), package_components(r["components"])
    tool = r.get("sbom_tool") or {}
    used = tool.get("used") or r.get("inventory_source")
    if used in (None, "none"):
        st.error("No SBOM could be generated for this scan (no Syft/Trivy and no parsable lockfiles/manifests).")
    else:
        label = {"syft": "Syft", "trivy": "Trivy", "builtin": "Built-in rule engine"}.get(used, used)
        ver = f" {tool.get('version')}" if tool.get("version") else ""
        st.caption(f"SBOM generated by **{label}{ver}** · requested scanner: `{tool.get('requested', 'auto')}`")

    fusion = r.get("metadata_fusion") or {}
    mm = fusion.get("integrity_mismatches") or []
    if mm:
        st.error(f"🚨 **{len(mm)}** lockfile digest(s) do not match the registry's digest for the same version (possible tampered lockfile or republished package). See the Metadata tab.")
    c = st.columns(5)
    c[0].metric("Components", len(comps), help="Software packages. CI actions and container images are listed on the Pipeline & Containers page.")
    c[1].metric("Inventory", (q.get("inventory_status") or "n/a").replace("_", " ").title())
    c[2].metric("Relationships", q.get("dependency_relationships", "n/a"))
    c[3].metric("Metadata completeness", f"{fusion['average_completeness']:.0%}" if fusion else (q.get("metadata_status") or "n/a").replace("_", " ").title())
    c[4].metric("Unresolved", q.get("unresolved_components", 0))

    t1, t_meta, t2, t3, t_raw, t4 = st.tabs(["Components", "Metadata", "Quality", "Scanner & validation", "SBOM file", "Downloads"])

    with t1:
        f1, f2, f3 = st.columns([1, 1, 2])
        ecos = sorted({x["ecosystem"] or x["purl_type"] or "unknown" for x in comps})
        sel_e = f1.multiselect("Ecosystem", ecos, placeholder="All ecosystems")
        svcs = sorted({x["service_dir"] or "." for x in comps})
        sel_s = f2.multiselect("Service", svcs, placeholder="All services")
        text = f3.text_input("Search package or PURL", placeholder="Filter by name...")

        rows = [x for x in comps if (not sel_e or (x["ecosystem"] or x["purl_type"] or "unknown") in sel_e)
                and (not sel_s or (x["service_dir"] or ".") in sel_s)
                and (not text or text.lower() in (x["name"] + (x["purl"] or "")).lower())]

        st.caption(f"Showing {len(rows)} of {len(comps)} components")
        df([{"Name": x["name"], "Version": x["version"], "Ecosystem": x["ecosystem"] or x["purl_type"],
             "Service": x["service_dir"], "License": ", ".join(x["licenses"]) or "n/a",
             "Scope": x.get("scope") or "n/a", "Integrity": (x.get("integrity") or {}).get("status") or "n/a",
             "Hash": "yes" if x.get("hashes") else "no", "Install script": "yes" if x.get("install_script") else "",
             "Resolution": x.get("resolution") or "scanner", "Complete": x.get("completeness") if x.get("completeness") is not None else None,
             "Supplier": x["supplier"] or "n/a", "PURL": x["purl"]} for x in rows], height=380)

        if rows:
            with st.expander("Component Inspector", expanded=False):
                pick = st.selectbox("Inspect component", [f"{x['name']}@{x['version']}" for x in rows[:300]])
                idx = [f"{x['name']}@{x['version']}" for x in rows[:300]].index(pick)
                sel = rows[idx]
                kv_table({k: v for k, v in sel.items() if k not in ("hashes", "provenance", "integrity", "external_refs", "enriched")})
                prov = {k: v for k, v in (sel.get("provenance") or {}).items() if not k.startswith("_")}
                if prov:
                    st.markdown("**Where each value came from**")
                    df([{"Field": k, "Source": v["source"], "Confidence": v.get("confidence"), "Evidence": v.get("evidence", ""),
                         "Conflicts": "; ".join(f"{c['source']}={c['value']}" for c in v.get("conflicts", []))} for k, v in prov.items()], height="content")
                miss = ((sel.get("provenance") or {}).get("_missing") or {}).get("reasons") or {}
                if miss:
                    st.markdown("**Missing, and why**")
                    df([{"Field": k, "Reason": v} for k, v in miss.items()], height="content")
                if sel.get("integrity"):
                    st.markdown("**Integrity**")
                    st.json(sel["integrity"])
                if sel.get("hashes"):
                    st.markdown("**Hashes**")
                    st.json(sel["hashes"])
                if sel.get("external_refs"):
                    st.markdown("**Links**")
                    df(sel["external_refs"], height="content")

    with t_meta:
        if not fusion:
            st.info("Metadata fusion did not run for this scan (no SBOM or an older stored scan). Rescan with 'Reuse cached scan' unticked.")
        else:
            st.caption("Every field keeps its source. Order of trust: lockfile (exact pin) > manifest > registry > SBOM scanner > inferred. A lower-trust value never overwrites a higher-trust one; disagreements are listed as conflicts.")
            cov = fusion["coverage"]
            df([{"Field": f.replace("_", " "), "Scanner only": c["before"], "After fusion": c["after"], "Of": fusion["components"], "Coverage %": c["percent"]} for f, c in cov.items()], height="content")
            a, b, c3 = st.columns(3)
            integ = fusion["integrity"]
            a.metric("Digest verified", integ.get("verified", 0), help="Lockfile digest equals the registry's digest for this exact version")
            b.metric("Digest mismatch", integ.get("mismatch", 0), help="Possible tampered lockfile or republished package")
            c3.metric("No lockfile digest", integ.get("absent", 0), help="Registry digest was added with medium confidence")
            if mm:
                st.markdown("**Integrity mismatches**")
                df(mm, height="content")
            reg = fusion.get("registry_phase") or {}
            if not reg.get("skipped"):
                st.caption(f"Registries: {reg.get('fetched', 0)} fetched · {reg.get('from_cache', 0)} cached · {reg.get('not_found', 0)} not found · {reg.get('unavailable', 0)} unavailable"
                           + (f" · tripped: {', '.join(reg['hosts_tripped'])}" if reg.get("hosts_tripped") else "") + (f" · no client for: {', '.join(reg['unsupported_ecosystems'])}" if reg.get("unsupported_ecosystems") else ""))
            rs = r.get("registry_resolution") or {}
            if rs.get("candidates"):
                st.markdown("**Registry resolution of manifest-only services** (no lockfile: transitive packages resolved by deps.dev; labelled `registry-resolved`)")
                st.caption(f"{rs['resolved']}/{rs['candidates']} pinned direct dependencies resolved -> {rs['derived_packages']} additional transitive packages. Each direct dependency is resolved on its own; the project's real version mediation may differ.")
            st.markdown("**Fields by source**")
            st.bar_chart(fusion.get("fields_by_source") or {})
            if fusion.get("install_script_packages"):
                with st.expander(f"{len(fusion['install_script_packages'])} package(s) run code at install time"):
                    st.write(", ".join(fusion["install_script_packages"]))
            if fusion.get("deprecated_packages"):
                with st.expander(f"{len(fusion['deprecated_packages'])} deprecated package(s)"):
                    st.write(", ".join(fusion["deprecated_packages"]))
            if fusion.get("conflict_count"):
                with st.expander(f"{fusion['conflict_count']} source conflict(s)"):
                    df([{"Component": x["component"], "Field": x["field"], "Chosen from": x["chosen"], "Other sources": "; ".join(f"{c['source']}={c['value']}" for c in x["conflicts"])} for x in fusion["conflicts"]], height=260)

    with t2:
        col_m1, col_m2 = st.columns(2)
        with col_m1:
            st.markdown(f"**Missing Lockfile Entries** ({q.get('lockfile_missing_from_sbom_count', 0)})")
            df(q.get("lockfile_missing_from_sbom", []), height=220)
        with col_m2:
            st.markdown(f"**SBOM Components Absent from Lockfiles** ({q.get('sbom_absent_from_lockfile_count', 0)})")
            df(q.get("sbom_absent_from_lockfile", []), height=220)

        st.caption(f"Relationships: {q.get('relationship_edges', 0)} edges recorded · {q.get('missing_relationships', 0)} components without relationships")

    with t3:
        v = r["sbom"].get("validation", {})
        st.markdown(f"**Spec:** CycloneDX {r['sbom'].get('spec_version') or 'n/a'} &nbsp;·&nbsp; **Valid:** {v.get('valid', False)} &nbsp;·&nbsp; **Components:** {v.get('stats', {}).get('components', 0)}")
        for e in v.get("errors", []):
            st.error(e)

        if tool.get("used") == "builtin":
            st.success("✅ **CycloneDX 1.5 SBOM generated successfully by SC Guardian's built-in rule engine** (100% in-process fallback; external Syft/Trivy CLI binaries are optional).")
        else:
            st.success(f"✅ **CycloneDX 1.5 SBOM generated successfully using {tool.get('used', 'scanner')}**.")

        st.markdown("**Scanner attempts** (in the order tried)")
        att = tool.get("attempts") or []

        def _format_result(a: dict) -> str:
            if a["ok"]:
                return "✓ Used"
            err = (a.get("error") or "").lower()
            if "not found" in err or "not installed" in err:
                return "○ Not installed (skipped)"
            return "✗ Failed"

        df([{"Scanner": a["scanner"], "Result": _format_result(a), "Version": a.get("version") or "—",
             "Seconds": a.get("duration_s"), "Detail": a.get("error") or "ok"} for a in att], height="content")
        for a in att:
            if a.get("command"):
                st.code(a["command"], language="bash")
        es = tool.get("engine_stats")
        if es:
            st.markdown("**Rule engine statistics** (rules R1–R6 in `sbom/builtin_generator.py`)")
            kv_table(es)
        av = tool.get("available") or {}
        if av:
            st.caption("Installed: " + ", ".join(f"{k}={'yes' if x else 'no'}" for k, x in av.items() if k != "builtin") + ". Install Syft/Trivy for broader coverage; see README.")

    with t_raw:
        files = r.get("sbom_files") or ([{"label": "SBOM", "path": r.get("sbom_path")}] if r.get("sbom_path") else [])
        sel_path = r.get("sbom_path")
        if len(files) > 1:
            pick = st.selectbox("SBOM file", range(len(files)), format_func=lambda i: files[i]["label"])
            sel_path = files[pick]["path"]
        raw = read_file(sel_path)
        if not raw:
            st.warning("The SBOM file is no longer on disk (artifacts were cleaned). Re-run the scan with *Reuse cached scan* unticked to regenerate it.")
        else:
            import json as _json
            text = raw.decode("utf-8", "replace")
            try:
                doc = _json.loads(text)
            except ValueError:
                doc = None
            st.caption(f"`{sel_path}` · {len(raw):,} bytes · exactly as written by the scanner")
            views = ["Full file", "Header", "Components", "Dependencies"] if doc else ["Full file"]
            view = st.radio("View", views, horizontal=True)
            if view == "Full file":
                lines = text.splitlines()
                per = 400
                pages = max(1, (len(lines) + per - 1) // per)
                pg = st.number_input(f"Page ({per} lines per page, {len(lines):,} lines)", 1, pages, 1)
                st.code(chr(10).join(lines[(pg - 1) * per: pg * per]), language="json", line_numbers=True)
            elif view == "Header":
                st.json({k: x for k, x in doc.items() if k not in ("components", "dependencies")})
            elif view == "Components":
                q_ = st.text_input("Filter components by name / purl", key="rawq").lower()
                items = [c for c in doc.get("components", []) if not q_ or q_ in (str(c.get("name")) + str(c.get("purl"))).lower()]
                size = 25
                pg = st.number_input(f"Page ({size} per page, {len(items)} components)", 1, max(1, (len(items) + size - 1) // size), 1)
                st.json(items[(pg - 1) * size: pg * size])
            else:
                deps = doc.get("dependencies", [])
                size = 40
                pg = st.number_input(f"Page ({size} per page, {len(deps)} records)", 1, max(1, (len(deps) + size - 1) // size), 1, key="dep_p")
                st.json(deps[(pg - 1) * size: pg * size])

    with t4:
        data = read_file(r.get("sbom_path"))
        if data:
            st.download_button(f"Download CycloneDX JSON ({used})", data, file_name=f"{r['repo']['name']}-sbom.cdx.json", mime="application/json", use_container_width=True)
        else:
            st.info("No SBOM artifact file available.")
